const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const data = JSON.parse(read('assets/languages/pt-BR.json'));
const sandbox = { window: {}, URL };
for (const script of ['data', 'project-deeplinks', 'project-content']) {
  vm.runInNewContext(read(`assets/js/${script}.js`), sandbox);
}
const { PortfolioProjectLinks: links, PortfolioProjectContent: content, portfolioConfig: config } = sandbox.window;
const { escape } = content;
const siteUrl = new URL(config.siteUrl.replace(/\/?$/, '/'));
if (!['https:', 'http:'].includes(siteUrl.protocol) || siteUrl.search || siteUrl.hash) {
  throw new Error('siteUrl must be an HTTP(S) URL without a query or fragment.');
}
const routes = { 'library.html': 'biblioteca/', 'resume.html': 'carreira/', 'recommendations.html': 'recomendacoes/' };
const headerPattern = /  <header class="site-header"[\s\S]*?<\/header>/;
const header = read('index.html').match(headerPattern)[0];
const urls = ['', ...Object.values(routes)];

function emit(file, value) {
  const target = path.join(root, file);
  if (fs.existsSync(target) && read(file) === value) return;
  if (check) {
    console.error(`Outdated page: ${file}`);
    process.exitCode = 1;
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, value);
}

function generated(html, route, base) {
  return '<!-- Generated by scripts/generate-pages.cjs -->\n' + html
    .replace('<head>', `<head>\n  <base href="${base}">`)
    .replace(/href="#([^"]+)"/g, (_, id) => `href="${route}#${id}"`);
}

function updateMetadata(html, route) {
  const canonical = html.match(/<link rel="canonical" href="([^"]+)">/)[1];
  const previousBase = canonical.slice(0, canonical.length - route.length);
  return html.replace(/<head>[\s\S]*?<\/head>/, (head) =>
    head.replaceAll(previousBase, siteUrl.href)
  );
}

emit('index.html', updateMetadata(read('index.html'), ''));
emit('404.html', read('404.html').replace(/<base href="[^"]*">/, `<base href="${escape(siteUrl.pathname)}">`));
emit('robots.txt', read('robots.txt').replace(/^Sitemap:.*$/m, `Sitemap: ${new URL('sitemap.xml', siteUrl)}`));

for (const [file, route] of Object.entries(routes)) {
  const source = updateMetadata(read(file), route).replace(headerPattern, () => header);
  emit(file, source);
  emit(route + 'index.html', generated(source, route, '../'));
}

const slugs = new Set();
for (const project of data.projects.filter((item) => !item.hidden)) {
  const slug = links.slugFor(project);
  if (!slug || slugs.has(slug)) throw new Error('Invalid project slug: ' + slug);
  slugs.add(slug);
  const route = links.projectPath(project);
  urls.push(route);
  const canonical = new URL(route, siteUrl).href;
  const title = escape(`${project.title} | ${config.profile.name}`);
  const description = escape(project.description);
  const cover = new URL(project.image || config.branding.socialPreview, siteUrl).href;
  const category = data.categories.find((item) => item.id === project.category)?.label;
  const structured = JSON.stringify({
    '@context': 'https://schema.org',
    '@type': 'CreativeWork',
    name: project.title,
    description: project.description,
    url: canonical,
    image: cover,
    keywords: [category, ...(project.stack || [])].filter(Boolean)
  }).replace(/</g, '\\u003c');
  const html = `<!doctype html>
<html lang="pt-BR">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${title}</title>
  <meta name="description" content="${description}">
  <link rel="canonical" href="${canonical}">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${title}">
  <meta property="og:description" content="${description}">
  <meta property="og:url" content="${canonical}">
  <meta property="og:image" content="${escape(cover)}">
  <meta name="twitter:card" content="summary_large_image">
  <script type="application/ld+json">${structured}</script>
  <link rel="icon" href="favicon.ico">
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/bootstrap-icons@1.13.1/font/bootstrap-icons.min.css">
  <link rel="stylesheet" href="assets/css/main.css">
  <link rel="stylesheet" href="assets/css/interface.css">
  <link rel="stylesheet" href="assets/css/project-page.css">
</head>
<body class="project-page">
  <a class="skip-link" href="#main-content">${escape(data.accessibility.skipToContent)}</a>
${header.replace('data-main-nav="library"', 'data-main-nav="library" aria-current="page"')}
  <main class="container project-main" id="main-content" tabindex="-1" data-project="${slug}">
${content.render(project, data, config, route)}
  </main>
${['data', 'analytics', 'navigation', 'project-deeplinks', 'project-content', 'pages-common', 'project-page', 'accessibility'].map((name) =>
  `  <script defer src="assets/js/${name}.js"></script>`).join('\n')}
</body>
</html>
`;
  emit(route + 'index.html', generated(html, route, '../../'));
}

emit('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.map((route) => `  <url><loc>${escape(new URL(route, siteUrl).href)}</loc></url>`).join('\n') + '\n</urlset>\n');
